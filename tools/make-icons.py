import re, sys, urllib.request, xml.etree.ElementTree as ET, math
VER="0.468.0"
# Windows Segoe Fluent glyph -> Lucide icon (the app's outlined look)
MAP = {
 "E711":"x","E713":"settings","E714":"video","E71A":"square","E71B":"link","E720":"mic","E722":"camera","E72C":"refresh-cw",
 "E72D":"share-2","E737":"app-window","E73E":"check","E74D":"trash-2","E74E":"save","E765":"keyboard","E767":"volume-2",
 "E768":"play","E769":"pause","E777":"rotate-ccw","E7BA":"triangle-alert","E7C8":"circle-dot","E7F4":"monitor","E7FC":"gamepad-2",
 "E838":"folder-open","E896":"download","E8B3":"list-checks","E8B9":"images","E9D9":"activity","F3B1":"log-out",
 "E70F":"pencil","E8C8":"copy","E7F0":"captions","E8C6":"scissors","E76B":"chevron-left","E76C":"chevron-right","E76E":"chevron-down","E70D":"chevron-down",
 "E712":"ellipsis","E710":"plus","E108":"play","E109":"pause",
 "E91B":"image","E8D2":"type","EDFB":"pen-line","E879":"shapes","ED1A":"droplet","E7A8":"crop","E762":"sliders-horizontal",
 "E72A":"arrow-right","E72B":"arrow-left","E739":"square","EA3A":"circle","E790":"palette","E71E":"search",
 "E7A7":"undo-2","E7A6":"redo-2","E783":"circle-alert","E74F":"volume-x","E8A7":"external-link","E7C2":"arrow-left","E8BB":"x","F5B0":"play","F8AE":"pause",
}
names = sorted(set(MAP.values()) | {"minus","square-dashed"})
ns = "{http://www.w3.org/2000/svg}"
def num(x): return ("%.4f" % x).rstrip("0").rstrip(".")
def circle(cx,cy,r): return f"M{num(cx-r)},{num(cy)}a{num(r)},{num(r)} 0 1,0 {num(2*r)},0a{num(r)},{num(r)} 0 1,0 {num(-2*r)},0Z"
def rect(x,y,w,h,rx,ry):
    rx=min(rx or ry or 0,w/2); ry=min(ry or rx or 0,h/2)
    if not rx: return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}Z"
    return (f"M{num(x+rx)},{num(y)}h{num(w-2*rx)}a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(ry)}v{num(h-2*ry)}a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(ry)}"
            f"h{num(-(w-2*rx))}a{num(rx)},{num(ry)} 0 0,1 {num(-rx)},{num(-ry)}v{num(-(h-2*ry))}a{num(rx)},{num(ry)} 0 0,1 {num(rx)},{num(-ry)}Z")
out=[]
for n in names:
    svg=urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/lucide-static@{VER}/icons/{n}.svg",timeout=30).read().decode()
    root=ET.fromstring(re.sub(r"<!--.*?-->","",svg,flags=re.S))
    d=[]
    for e in root.iter():
        t=e.tag.replace(ns,""); a=e.attrib
        if t=="path":
            p=a["d"].strip()
            # A path that starts with a relative "m" is absolute for its first point; as part of one joined path it would
            # be relative to the previous sub-path's end.
            m=re.match(r"m\s*(-?[\d.]+)[ ,]\s*(-?[\d.]+)(.*)$",p,re.S)
            if m: p="M"+m.group(1)+" "+m.group(2)+(" l"+m.group(3) if m.group(3).strip() else "")
            d.append(p)
        elif t=="circle": d.append(circle(float(a["cx"]),float(a["cy"]),float(a["r"])))
        elif t=="ellipse":
            cx,cy,rx,ry=[float(a[k]) for k in("cx","cy","rx","ry")]
            d.append(f"M{num(cx-rx)},{num(cy)}a{num(rx)},{num(ry)} 0 1,0 {num(2*rx)},0a{num(rx)},{num(ry)} 0 1,0 {num(-2*rx)},0Z")
        elif t=="rect": d.append(rect(float(a["x"]),float(a["y"]),float(a["width"]),float(a["height"]),float(a.get("rx",0)),float(a.get("ry",0))))
        elif t=="line": d.append(f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}")
        elif t in("polyline","polygon"):
            pts=re.split(r"[ ,]+",a["points"].strip()); xs=list(zip(pts[0::2],pts[1::2]))
            d.append("M"+"L".join(f"{x},{y}" for x,y in xs)+("Z" if t=="polygon" else ""))
    out.append((n," ".join(d)))
xaml='<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
xaml+='    <!-- Lucide icons (ISC licence, https://lucide.dev), drawn as 2 px strokes on a 24 x 24 grid. Generated by tools/make-icons.py -->\n'
for n,d in out: xaml+=f'    <StreamGeometry x:Key="icon-{n}">{d}</StreamGeometry>\n'
xaml+='</ResourceDictionary>\n'
open("Icons.axaml","w").write(xaml)
cs="namespace Kairos.Ui;\n\n/// <summary>The icon a Windows Segoe Fluent glyph code stands for (generated by tools/make-icons.py).</summary>\npublic static class IconMap\n{\n    public static readonly IReadOnlyDictionary<string, string> Glyphs = new Dictionary<string, string>\n    {\n"
for k,v in MAP.items(): cs+=f'        ["{k}"] = "{v}",\n'
cs+="    };\n}\n"
open("IconMap.cs","w").write(cs)
print(len(out),"icons")
